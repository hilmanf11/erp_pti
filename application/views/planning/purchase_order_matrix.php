<script>
    function filter() {
        var filter_year = $("#filter_year").combobox('getValue');
        var filter_product_family = $("#filter_product_family").combobox('getValue');

        var url = "?filter_year=" + window.btoa(filter_year) +
            "&filter_product_family=" + window.btoa(filter_product_family);

        if (filter_year == "") {
            toastr.warning("Please Choose Filter Year!", "Information");
        } else {
            $("#printout").contents().find('html').html("<center><br><br><br><b style='font-size:20px;'>Please Wait...</b></center>");
            $("#printout").attr('src', '<?= base_url('planning/purchase_order_matrix/print') ?>' + url);
        }
    }

    function pdf() {
        $("#printout").get(0).contentWindow.print();
    }

    function excel() {
        var filter_year = $("#filter_year").combobox('getValue');
        var filter_product_family = $("#filter_product_family").combobox('getValue');

        var url = "?filter_year=" + window.btoa(filter_year) +
            "&filter_product_family=" + window.btoa(filter_product_family);

        if (filter_year == "") {
            toastr.warning("Please Choose Filter Year!", "Information");
        } else {
            window.location.assign('<?= base_url('planning/purchase_order_matrix/print/excel') ?>' + url);
        }
    }

    function reload() {
        window.location.reload();
    }

    $(function() {
        $('#filter_year').combobox({
            url: '<?php echo base_url('planning/mst_data/readYears'); ?>',
            valueField: 'id',
            textField: 'name',
            prompt: 'Select Year',
            icons: [{
                iconCls: 'icon-clear',
                handler: function(e) {
                    $(e.data.target).combobox('clear').combobox('textbox').focus();
                }
            }],
        });

        $('#filter_product_family').combobox({
            url: '<?php echo base_url('planning/generate_mrp/readProductFamily'); ?>',
            valueField: 'pfm_id',
            textField: 'pfm_name',
            prompt: 'Select Product Family',
            icons: [{
                iconCls: 'icon-clear',
                handler: function(e) {
                    $(e.data.target).combobox('clear').combobox('textbox').focus();
                }
            }],
        });
    });

    function numberformat(value, row) {
        const formatter = new Intl.NumberFormat('id-ID', {
            minimumFractionDigits: 0
        });

        return "<b>" + formatter.format(value) + "</b>";
    }

</script>